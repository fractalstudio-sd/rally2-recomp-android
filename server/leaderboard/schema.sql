CREATE TABLE IF NOT EXISTS results (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  player TEXT NOT NULL,          -- random id generated by the app on first start
  name TEXT NOT NULL,            -- the three letters entered in the game
  board TEXT NOT NULL,           -- 'championship' or 'course:N'
  kind TEXT NOT NULL,            -- championship | stage | practice
  course INTEGER NOT NULL,
  course_name TEXT,
  car INTEGER NOT NULL,
  car_name TEXT,
  gear TEXT NOT NULL,
  time INTEGER NOT NULL,         -- 1/6000 s
  ts INTEGER,                    -- when it was driven (device clock)
  created INTEGER NOT NULL,      -- when it was received
  app TEXT
);
CREATE INDEX IF NOT EXISTS ix_board_time ON results(board, time);
CREATE INDEX IF NOT EXISTS ix_player_created ON results(player, created);
