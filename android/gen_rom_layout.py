#!/usr/bin/env python3
"""Regenerates app/src/main/java/org/srally2/RomLayout.java from ../data/srally2.json (run: python3 android/gen_rom_layout.py)."""
import json, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
j = json.load(open(os.path.join(root, 'data', 'srally2.json')))
L = ['// GENERATED by android/gen_rom_layout.py from data/srally2.json - ROM layout metadata only (names, offsets, CRC32), no ROM content.',
     'package org.srally2;', '', 'final class RomLayout {',
     '    static final class F { final String name; final long off; final long crc; final int len; F(String n, long o, long c, int l) { name = n; off = o; crc = c; len = l; } }',
     '    static final class R { final String name; final int stride, chunk; final boolean swap; final F[] files;',
     '        R(String n, int s, int c, boolean w, F... f) { name = n; stride = s; chunk = c; swap = w; files = f; } }',
     '    static final String[] REQUIRED = { %s };' % ', '.join('"%s"' % r['name'] for r in j['regions']),
     '    static final R[] REGIONS = {']
for r in j['regions']:
    stride, chunk, swap = r['stride'], r['chunk_size'], r['byte_swap']
    if swap and stride == 1 and chunk == 1: stride = chunk = 2   # Supermodel GameLoader special case (same as tools/build_images.py)
    fs = ', '.join('new F("%s", %dL, %dL, %d)' % (f['name'], f['offset'], f['crc32'], f['size']) for f in r['files'])
    L.append('        new R("%s", %d, %d, %s,\n            %s),' % (r['name'], stride, chunk, 'true' if swap else 'false', fs))
L += ['    };', '}', '']
open(os.path.join(root, 'android/app/src/main/java/org/srally2/RomLayout.java'), 'w').write('\n'.join(L))
