#!/usr/bin/env bash
# Build the Android APK (arm64). Run scripts/setup.sh first (ROM -> lifted code, same as the desktop build).
#   android/build.sh            build  -> build/srally2.apk
#   android/build.sh install    build, then adb install -r
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/.." && pwd)"
SDLV=2.30.9
die() { echo "error: $*" >&2; exit 1; }

[ -f "$ROOT/build/out/recomp_dispatch.c" ] || die "no lifted code in build/out - run scripts/setup.sh /path/to/srally2.zip first"

# --- JDK 17..21 (Android Gradle Plugin 8.5)
pick_jdk() {
  for c in "${JAVA_HOME:-}" "$(/usr/libexec/java_home -v 17 2>/dev/null || true)" "$(/usr/libexec/java_home -v 21 2>/dev/null || true)" \
           /opt/homebrew/opt/openjdk@17 /opt/homebrew/opt/openjdk@21 /usr/lib/jvm/java-17-openjdk-amd64 /usr/lib/jvm/java-21-openjdk-amd64 \
           "/Applications/Android Studio.app/Contents/jbr/Contents/Home"; do
    [ -n "$c" ] && [ -x "$c/bin/java" ] || continue
    v=$("$c/bin/java" -version 2>&1 | head -1 | sed -E 's/.*"([0-9]+).*/\1/')
    if [ "$v" -ge 17 ] && [ "$v" -le 21 ]; then export JAVA_HOME="$c"; return 0; fi
  done
  die "need a JDK 17-21 (brew install openjdk@17, or install Android Studio)"
}
pick_jdk

# --- Android SDK
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
[ -n "$SDK" ] || for c in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk"; do [ -d "$c" ] && SDK="$c" && break; done
[ -n "$SDK" ] && [ -d "$SDK" ] || die "Android SDK not found: install Android Studio (or set ANDROID_HOME)"
export ANDROID_HOME="$SDK"
SM="$SDK/cmdline-tools/latest/bin/sdkmanager"
if [ ! -x "$SM" ]; then SM="$(ls "$SDK"/cmdline-tools/*/bin/sdkmanager 2>/dev/null | head -1 || true)"; fi
[ -x "${SM:-}" ] || die "Android command-line tools missing: Android Studio > Settings > Android SDK > SDK Tools > 'Android SDK Command-line Tools'"
echo "== SDK packages"
yes | "$SM" --licenses >/dev/null 2>&1 || true
"$SM" "platforms;android-34" "build-tools;34.0.0" "platform-tools" "ndk;26.1.10909125" "cmake;3.22.1" >/dev/null
echo "sdk.dir=$SDK" > "$HERE/local.properties"

# --- SDL2 source (zlib licence), pinned to the version of the vendored Java glue
if [ ! -f "$HERE/app/jni/SDL2/CMakeLists.txt" ]; then
  echo "== downloading SDL2 $SDLV"
  T="$(mktemp -d)"; curl -fsSL -o "$T/sdl.tgz" "https://github.com/libsdl-org/SDL/releases/download/release-$SDLV/SDL2-$SDLV.tar.gz"
  tar -xzf "$T/sdl.tgz" -C "$T"; rm -rf "$HERE/app/jni/SDL2"; mv "$T/SDL2-$SDLV" "$HERE/app/jni/SDL2"; rm -rf "$T"
fi

# --- Musashi (68000) tables are generated by a tool that must run on THIS machine, not on the phone
M="$ROOT/build/android/musashi"
if [ ! -f "$M/m68kops.c" ]; then
  echo "== generating Musashi tables"
  mkdir -p "$M/src"; cp -R "$ROOT/runtime/hw/CPU/68K/Musashi/." "$M/src/"
  cc -w -o "$M/m68kmake" "$ROOT/runtime/hw/CPU/68K/Musashi/m68kmake.c"
  (cd "$M" && ./m68kmake "$M" "$M/src/m68k_in.c")
fi

echo "== building APK (first build compiles ~11 MB of lifted code: a few minutes)"
cd "$HERE"
[ -f "$HERE/app/src/main/res/mipmap-xxxhdpi/ic_launcher.png" ] || python3 "$HERE/make_icon.py" || die "app icon: pip3 install pillow (or put your own icon.png next to build.sh)"
./gradlew --no-daemon assembleRelease -Pm3.generated="$ROOT/build/out" -Pm3.musashi="$M"
mkdir -p "$ROOT/build"; cp app/build/outputs/apk/release/app-release.apk "$ROOT/build/srally2.apk"
echo "== done: $ROOT/build/srally2.apk"
[ "${1:-}" = install ] && { "$SDK/platform-tools/adb" install -r "$ROOT/build/srally2.apk"; echo "installed; now run android/push_images.sh"; }
exit 0
